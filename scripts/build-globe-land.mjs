#!/usr/bin/env node
/**
 * Generates the land-dot data for the homepage globe
 * (features/elora-home/data/globeLand*.ts).
 *
 * Takes the country outlines that ship with the `world-countries` package
 * (ODbL — see the notice written into the output), samples an even
 * Fibonacci lattice over the sphere, and keeps the lattice points that fall
 * on land. The result is a list of [lat, lon] pairs, stored as integers in
 * tenths of a degree to keep the files small.
 *
 * Two densities:
 *   - DENSE  for the Three.js globe (desktop, lazily loaded)
 *   - COARSE for the server-rendered SVG globe (every device)
 *
 * Run: node scripts/build-globe-land.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const dataDir = join(root, "node_modules", "world-countries", "data")
const outDir = join(root, "features", "elora-home", "data")

/* ---------------------------------------------------------------- polygons */

const polygons = [] // { bbox: [minLon, minLat, maxLon, maxLat], rings: [[lon, lat][]] }

for (const file of readdirSync(dataDir)) {
    if (!file.endsWith(".geo.json")) continue
    const geo = JSON.parse(readFileSync(join(dataDir, file), "utf8"))
    for (const f of geo.features ?? []) {
        const g = f.geometry
        if (!g) continue
        const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : []
        for (const rings of polys) {
            let minLon = 180, minLat = 90, maxLon = -180, maxLat = -90
            for (const [lon, lat] of rings[0]) {
                if (lon < minLon) minLon = lon
                if (lon > maxLon) maxLon = lon
                if (lat < minLat) minLat = lat
                if (lat > maxLat) maxLat = lat
            }
            polygons.push({ bbox: [minLon, minLat, maxLon, maxLat], rings })
        }
    }
}

/** Ray casting; holes (rings after the first) subtract. */
function inRing(lon, lat, ring) {
    let inside = false
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i]
        const [xj, yj] = ring[j]
        if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
    }
    return inside
}

function onLand(lon, lat) {
    for (const p of polygons) {
        const [a, b, c, d] = p.bbox
        if (lon < a || lon > c || lat < b || lat > d) continue
        if (!inRing(lon, lat, p.rings[0])) continue
        let hole = false
        for (let k = 1; k < p.rings.length; k++) if (inRing(lon, lat, p.rings[k])) { hole = true; break }
        if (!hole) return true
    }
    return false
}

/* ----------------------------------------------------------------- sample */

function sample(n) {
    const golden = Math.PI * (3 - Math.sqrt(5))
    const out = []
    for (let i = 0; i < n; i++) {
        const y = 1 - (i / (n - 1)) * 2
        const lat = (Math.asin(y) * 180) / Math.PI
        let lon = (((golden * i) % (2 * Math.PI)) * 180) / Math.PI
        if (lon > 180) lon -= 360
        if (onLand(lon, lat)) out.push(Math.round(lat * 10), Math.round(lon * 10))
    }
    return out
}

const NOTICE = `/**
 * GENERATED by scripts/build-globe-land.mjs — do not edit by hand.
 *
 * Land dots for the homepage globe: [lat, lon] pairs in tenths of a degree,
 * flattened. Derived from the country outlines in the \`world-countries\`
 * package (https://github.com/mledoze/countries), made available under the
 * Open Database License (ODbL) 1.0. The globe shows a matching credit.
 */`

for (const [name, n, file] of [
    ["LAND_DENSE", 26000, "globeLandDense.ts"],
    ["LAND_COARSE", 5200, "globeLand.ts"],
]) {
    const pts = sample(n)
    const body = `${NOTICE}\n\n// ${pts.length / 2} points from a ${n}-point lattice.\nexport const ${name}: readonly number[] = [${pts.join(",")}]\n`
    writeFileSync(join(outDir, file), body)
    console.log(`${file}: ${pts.length / 2} land points, ${(body.length / 1024).toFixed(1)} KB`)
}
